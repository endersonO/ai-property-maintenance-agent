import { z } from "zod";
import type { Repository, Review, Ticket } from "@/domain/repository";
import { evaluators as defaultEvaluators } from "@/evaluators";
import { evaluateRun, snapshotFromResult, type EvaluationStore, type Evaluator } from "@/runtime/evaluation";
import type { ModelPort } from "@/runtime/model";
import { runAgent } from "@/runtime/orchestrator";
import type { TraceStore } from "@/runtime/tracing";
import { workflowIds, workflows } from "@/workflows";
import { checkAccess } from "./access";
import type { SlidingWindowLimiter } from "./limits";

// Chat use case behind POST /api/chat, kept free of Next.js so it can be tested directly.

export const ChatRequest = z.strictObject({
  // Simulated session: the portal's tenant selector. Real auth would set this server-side.
  tenantId: z.string().min(1),
  workflow: z.enum(workflowIds).default("maintenance"),
  // Generated by the client per message and reused on retries (idempotency).
  requestId: z.uuid(),
  message: z.string().trim().min(1).max(1000),
  // The server keeps no conversation; the client sends prior text turns.
  history: z
    .array(z.strictObject({ role: z.enum(["user", "assistant"]), content: z.string().max(2000) }))
    .max(20)
    .default([]),
});

export type ChatDeps = {
  repo: Repository;
  traces: TraceStore;
  model: ModelPort;
  // Deterministic abuse limits, checked before the model is called.
  limiter: SlidingWindowLimiter;
  // When set (public demo), requests must present it; failed attempts are limited per client.
  accessCode?: string;
  accessLimiter?: SlidingWindowLimiter;
  // Run deadline. Below the route's maxDuration, so the run fails cleanly before the platform kills it.
  timeoutMs?: number;
  // Online horizontal evaluation. Without a store, runs stay pending until the backfill.
  evaluations?: EvaluationStore;
  evaluators?: Evaluator[];
  // Time the reply may wait for verdicts to be saved; past it they are left to the backfill.
  evaluationBudgetMs?: number;
};

export type TicketSummary = {
  id: string;
  category: string;
  priority: string;
  status: string;
  hazards: string[];
  location: string | null;
  description: string;
  createdAt: string;
  // Tenant-facing explanation when a person at the agency must review the ticket.
  review: string | null;
};

export type ChatResponse =
  | { status: 400; body: { error: "invalid_request"; issues: string } }
  | { status: 401; body: { error: "access_code_required" } }
  | { status: 429; body: { error: "too_many_attempts" } }
  | { status: 429; body: { error: "rate_limited"; retryAfterSeconds: number } }
  | { status: 404; body: { error: "unknown_tenant" } }
  | {
      status: 200;
      body: {
        runId: string;
        outcome: "completed" | "failed";
        reply: string;
        tickets: TicketSummary[];
        // Tickets created or escalated by this message, so the portal can attach safety guidance.
        createdTicketIds: string[];
      };
    };

// Review reasons are written for operators ("rule 0 (emergency) requires review");
// tenants get a plain sentence instead.
function tenantReviewReason(ticket: Ticket, review: Review): string {
  if (review.source === "agent") return "The assistant asked a person at the agency to check this.";
  if (ticket.priority === "emergency") return "Emergencies are always checked by a person at the agency.";
  if (review.reason.includes("estimated cost")) {
    return "A person at the agency will approve the repair before it is booked.";
  }
  return "A person at the agency will check this before it goes ahead.";
}

export function toTicketSummaries(tickets: Ticket[], reviews: Review[]): TicketSummary[] {
  return tickets.map((t) => {
    const review = reviews.find((r) => r.ticketId === t.id);
    return {
      id: t.id,
      category: t.category,
      priority: t.priority,
      status: t.status,
      hazards: t.hazards,
      location: t.location,
      description: t.description,
      createdAt: t.createdAt.toISOString(),
      review: review ? tenantReviewReason(t, review) : null,
    };
  });
}

// When a run fails, never invent a reply — but don't claim nothing happened either:
// the run may have created a ticket before failing (e.g. the final model call timed out).
const FAILED_AFTER_TICKET =
  "I couldn't finish my reply, but your request was recorded. You can see it in your tickets below.";
const FAILED_AFTER_REVIEW =
  "I couldn't finish my reply, but I've asked a person at the agency to look at this.";
const FAILED_NOTHING_WRITTEN = "Sorry, something went wrong and nothing was changed. Please try again.";
// A tool was still running at the deadline: its write may land after we answer.
const FAILED_OUTCOME_UNKNOWN =
  "Sorry, this took too long. Your request may still be recorded: check your tickets in a minute before sending it again.";

export async function handleChat(
  input: unknown,
  deps: ChatDeps,
  request: { accessCode: string | null; client: string } = { accessCode: null, client: "local" },
): Promise<ChatResponse> {
  const access = checkAccess(request.accessCode, request.client, deps.accessCode, deps.accessLimiter);
  if (access === "locked") return { status: 429, body: { error: "too_many_attempts" } };
  if (access === "denied") return { status: 401, body: { error: "access_code_required" } };
  const parsed = ChatRequest.safeParse(input);
  if (!parsed.success) {
    return { status: 400, body: { error: "invalid_request", issues: z.prettifyError(parsed.error) } };
  }
  const { tenantId, workflow, requestId, message, history } = parsed.data;

  const tenant = await deps.repo.getTenantContext(tenantId);
  if (!tenant) return { status: 404, body: { error: "unknown_tenant" } };

  const allowed = deps.limiter.take(tenantId);
  if (!allowed.ok) {
    return { status: 429, body: { error: "rate_limited", retryAfterSeconds: Math.ceil(allowed.retryAfterMs / 1000) } };
  }

  const result = await runAgent({
    workflow: workflows[workflow],
    model: deps.model,
    deps: { repo: deps.repo },
    tenantId,
    requestId,
    userMessage: message,
    history: history.map((turn) =>
      turn.role === "user"
        ? { role: "user" as const, content: turn.content }
        : { role: "assistant" as const, content: turn.content, toolCalls: [] },
    ),
    timeoutMs: deps.timeoutMs ?? 50_000,
    trace: { store: deps.traces, meta: { source: "portal", agencyId: tenant.agency.id } },
  });

  await evaluateOnline(deps, result, { workflowId: workflow, tenantId, agencyId: tenant.agency.id, userMessage: message });

  const [tickets, reviews] = await Promise.all([deps.repo.listTickets(tenantId), deps.repo.listReviews(tenantId)]);
  // A failed run may already have written something: say what was kept, never "nothing".
  const ticketInThisRun = tickets.some((t) => t.runId === result.runId);
  const reviewInThisRun = reviews.some((r) => r.runId === result.runId);
  const reply =
    result.status === "completed" && result.output
      ? result.output
      : ticketInThisRun
        ? FAILED_AFTER_TICKET
        : reviewInThisRun
          ? FAILED_AFTER_REVIEW
          : result.error === "tool_timeout"
            ? FAILED_OUTCOME_UNKNOWN
            : FAILED_NOTHING_WRITTEN;

  return {
    status: 200,
    body: {
      runId: result.runId,
      outcome: result.status,
      reply,
      tickets: toTicketSummaries(tickets, reviews),
      createdTicketIds: tickets
        .filter((t) => t.runId === result.runId || reviews.some((r) => r.runId === result.runId && r.ticketId === t.id))
        .map((t) => t.id),
    },
  };
}

// Best effort, bounded: verdicts are evaluated from the run's snapshot and saved within a
// small budget. A slow or failing store never changes the tenant's reply; the run then has
// no verdict (shown as pending, never as passing) and the backfill picks it up.
async function evaluateOnline(
  deps: ChatDeps,
  result: Awaited<ReturnType<typeof runAgent>>,
  meta: { workflowId: string; tenantId: string; agencyId: string; userMessage: string },
): Promise<void> {
  if (!deps.evaluations || result.error === "trace_unavailable") return;
  let timer: ReturnType<typeof setTimeout> | undefined;
  try {
    const snapshot = snapshotFromResult(result, { ...meta, source: "portal" });
    const verdicts = evaluateRun(snapshot, deps.evaluators ?? defaultEvaluators);
    const budget = new Promise<never>((_, reject) => {
      timer = setTimeout(() => reject(new Error("evaluation budget exceeded")), deps.evaluationBudgetMs ?? 300);
    });
    await Promise.race([deps.evaluations.save(verdicts), budget]);
  } catch (error) {
    console.error(`Online evaluation skipped for run ${result.runId}; the backfill will retry`, error);
  } finally {
    clearTimeout(timer);
  }
}
