import { z } from "zod";
import type { Repository, Review, Ticket } from "@/domain/repository";
import type { ModelPort } from "@/runtime/model";
import { runAgent } from "@/runtime/orchestrator";
import type { TraceStore } from "@/runtime/tracing";
import { workflowIds, workflows } from "@/workflows";

// Chat use case behind POST /api/chat, kept free of Next.js so it can be tested directly.

export const ChatRequest = z.strictObject({
  // Simulated session: the portal's tenant selector. Real auth would set this server-side.
  tenantId: z.string().min(1),
  workflow: z.enum(workflowIds).default("maintenance"),
  // Generated by the client per message and reused on retries (idempotency).
  requestId: z.uuid(),
  message: z.string().trim().min(1).max(1000),
  // The server keeps no conversation; the client sends prior text turns.
  history: z
    .array(z.strictObject({ role: z.enum(["user", "assistant"]), content: z.string().max(2000) }))
    .max(20)
    .default([]),
});

export type ChatDeps = { repo: Repository; traces: TraceStore; model: ModelPort };

export type TicketSummary = {
  id: string;
  category: string;
  priority: string;
  status: string;
  hazards: string[];
  location: string | null;
  description: string;
  createdAt: string;
  // Tenant-facing explanation when a person at the agency must review the ticket.
  review: string | null;
};

export type ChatResponse =
  | { status: 400; body: { error: "invalid_request"; issues: string } }
  | { status: 404; body: { error: "unknown_tenant" } }
  | {
      status: 200;
      body: {
        runId: string;
        outcome: "completed" | "failed";
        reply: string;
        tickets: TicketSummary[];
        // Tickets created by this message, so the portal can attach safety guidance.
        createdTicketIds: string[];
      };
    };

// Review reasons are written for operators ("rule 0 (emergency) requires review");
// tenants get a plain sentence instead.
function tenantReviewReason(ticket: Ticket, review: Review): string {
  if (review.source === "agent") return "The assistant asked a person at the agency to check this.";
  if (ticket.priority === "emergency") return "Emergencies are always checked by a person at the agency.";
  if (review.reason.includes("estimated cost")) {
    return "A person at the agency will approve the repair before it is booked.";
  }
  return "A person at the agency will check this before it goes ahead.";
}

export function toTicketSummaries(tickets: Ticket[], reviews: Review[]): TicketSummary[] {
  return tickets.map((t) => {
    const review = reviews.find((r) => r.ticketId === t.id);
    return {
      id: t.id,
      category: t.category,
      priority: t.priority,
      status: t.status,
      hazards: t.hazards,
      location: t.location,
      description: t.description,
      createdAt: t.createdAt.toISOString(),
      review: review ? tenantReviewReason(t, review) : null,
    };
  });
}

// When a run fails, never invent a reply — but don't claim nothing happened either:
// the run may have created a ticket before failing (e.g. the final model call timed out).
const FAILED_AFTER_WRITE =
  "I couldn't finish my reply, but your request was recorded. You can see it in your tickets below.";
const FAILED_NOTHING_WRITTEN = "Sorry, something went wrong and nothing was changed. Please try again.";

export async function handleChat(input: unknown, deps: ChatDeps): Promise<ChatResponse> {
  const parsed = ChatRequest.safeParse(input);
  if (!parsed.success) {
    return { status: 400, body: { error: "invalid_request", issues: z.prettifyError(parsed.error) } };
  }
  const { tenantId, workflow, requestId, message, history } = parsed.data;

  const tenant = await deps.repo.getTenantContext(tenantId);
  if (!tenant) return { status: 404, body: { error: "unknown_tenant" } };

  const result = await runAgent({
    workflow: workflows[workflow],
    model: deps.model,
    deps: { repo: deps.repo },
    tenantId,
    requestId,
    userMessage: message,
    history: history.map((turn) =>
      turn.role === "user"
        ? { role: "user" as const, content: turn.content }
        : { role: "assistant" as const, content: turn.content, toolCalls: [] },
    ),
    // Below the route's maxDuration, so the run fails cleanly before the platform kills it.
    timeoutMs: 50_000,
    trace: { store: deps.traces, meta: { source: "portal", agencyId: tenant.agency.id } },
  });

  const [tickets, reviews] = await Promise.all([deps.repo.listTickets(tenantId), deps.repo.listReviews(tenantId)]);
  const wroteInThisRun = tickets.some((t) => t.runId === result.runId);
  const reply =
    result.status === "completed" && result.output
      ? result.output
      : wroteInThisRun
        ? FAILED_AFTER_WRITE
        : FAILED_NOTHING_WRITTEN;

  return {
    status: 200,
    body: {
      runId: result.runId,
      outcome: result.status,
      reply,
      tickets: toTicketSummaries(tickets, reviews),
      createdTicketIds: tickets.filter((t) => t.runId === result.runId).map((t) => t.id),
    },
  };
}
